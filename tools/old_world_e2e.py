#!/usr/bin/env python3
"""A world with chunks an older version generated, played in the real game.

Chunks of a world with one seed are copied into a world with another seed,
each with the `blending_data` that marks it as generated by an older version
(tools: the old_world_fixture example). The game then generates the chunks
around them, and they blend with the old terrain (`Blender.of`) instead of
meeting it in a cliff. The same world is opened with blending disabled
(HORIZON_DISABLE_BLENDING, vanilla's DEBUG_DISABLE_BLENDING) for comparison.

usage: old_world_e2e.py [--out DIR]
"""
import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import lab  # noqa: E402
import lan_e2e as lan  # noqa: E402

SOURCE_SEED, TARGET_SEED = 111, 4242
# The old chunks: west of x = 0, the new ones generate to the east.
OLD_RECT = '-8,-8,-1,8'
SHOTS = [  # label, x, y, z, yaw, pitch
    ('along-the-border', 0.5, 150, 64.5, 180, 32),
    ('from-the-new-side', 40.5, 160, 0.5, 90, 30),
]


def game(ctl, resources, name, env=None):
    g = lan.Game(name, ctl, resources)
    # The scratch folders lan_e2e gave it stay; `env` is added on top.
    g.d.env.update(lab.game_env(g.d.env, **(env or {})))
    return g


def close(g):
    g.close()


def build():
    subprocess.run(['cargo', 'build', '--locked', '--profile', 'fast', '-p', 'horizon-client', '-p', 'horizon-client-lib',
                    '--bin', 'horizon-client', '--bin', 'horizon-ctl', '--example', 'old_world_fixture'], cwd=lan.ROOT, check=True)
    meta = json.loads(subprocess.run(['cargo', 'metadata', '--format-version', '1', '--no-deps'], cwd=lan.ROOT,
                                     capture_output=True, text=True, check=True).stdout)
    return Path(meta['target_directory']) / 'fast'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', default=str(lan.ROOT / '.local/old-world-e2e'))
    args = parser.parse_args()
    out = Path(args.out).resolve()
    out.mkdir(parents=True, exist_ok=True)
    bins = build()
    ctl, resources = bins / 'horizon-ctl', lab.RESOURCES.resolve()
    # 1. The source world: terrain of one seed around the origin.
    src = game(ctl, resources, 'source')
    try:
        src.raw('launch', '--offscreen')
        src.raw('open', 'Src', SOURCE_SEED, 'creative')
        src('wait_ready', seconds=400)
        src('command', command='tp @s 0 120 0')
        src.wait(400)
    finally:
        close(src)
    # 2. The destination world: another seed, its level.dat.
    dst = game(ctl, resources, 'destination')
    try:
        dst.raw('launch', '--offscreen')
        dst.raw('open', 'Dst', TARGET_SEED, 'creative')
        dst('wait_ready', seconds=400)
    finally:
        close(dst)
    source_world, target_world = src.work / 'saves' / 'Src', dst.work / 'saves' / 'Dst'
    made = subprocess.run([str(bins / 'examples' / 'old_world_fixture'), str(source_world), str(target_world), OLD_RECT],
                          check=True, capture_output=True, text=True).stdout.strip()
    print('fixture:', made)
    assert not made.startswith('0 '), 'no old chunks were made'
    # 3. The same world, with blending and without.
    for label, env in (('blended', {}), ('not-blended', {'HORIZON_DISABLE_BLENDING': '1'})):
        g = game(ctl, resources, label, env)
        shutil.copytree(target_world, g.work / 'saves' / 'Dst')
        try:
            g.raw('launch', '--offscreen')
            g.raw('open', 'Dst')
            g('wait_ready', seconds=400)
            g('command', command='gamemode spectator')
            # The chunk strip next to the old chunks is decorated like any other: it has trees.
            logs = 0
            for z0 in range(-32, 32, 16):  # a request holds at most 32768 blocks
                counts = g.raw('blocks', 0, 60, z0, 15, 187, z0 + 15).get('counts', {})
                logs += sum(n for block, n in counts.items() if block.endswith('_log'))
            print(label, 'logs in the new chunk strip at the border:', logs)
            if label == 'blended':
                assert logs > 0, 'no tree grew in the chunk strip beside the old chunks'
            for shot, x, y, z, yaw, pitch in SHOTS:
                g('command', command=f'tp @s {x} {y} {z} {yaw} {pitch}')
                g.wait(500)
                g.raw('key', 'f1', 'tap')
                g.wait(5)
                print(label, shot, 'at', g('state')['player']['position'])
                g.shot(out, shot)
                g.raw('key', 'f1', 'tap')
        finally:
            close(g)
    print(f'screenshots in {out}')


if __name__ == '__main__':
    main()
