#!/usr/bin/env python3
"""Generate crates/horizon-protocol/src/adapter/v<OLD>.rs: how an older release numbers the packets of each
connection state against the pinned one, from both versions' data generator packets reports.

    generate_packet_id_adapter.py --old ~/code/horizon-parity/versions/26.2

`--old` (and `--new`, the pinned version in .local by default) is a directory `tools/version_port.py prepare
VERSION --download` made: `jars/client.jar` and `datagen/reports/packets.json`.
Packets are matched by name, as both reports list them; a packet only one version has maps to `None`.
"""

import argparse
import json
from pathlib import Path

try:
    from . import lab
except ImportError:
    import lab

ROOT = Path(__file__).resolve().parents[1]
STATES = ["handshake", "status", "login", "configuration", "play"]
PER_LINE = 12


def ids(report, state, direction):
    """{name: id} of one state and direction, checked to number its packets 0..n."""
    packets = {name: entry["protocol_id"] for name, entry in report.get(state, {}).get(direction, {}).items()}
    assert sorted(packets.values()) == list(range(len(packets))), (state, direction)
    return packets


def table(source, target):
    """For each id of `source` (in order), the id `target` gives the same packet, or None."""
    by_id = sorted(source.items(), key=lambda kv: kv[1])
    return [target.get(name) for name, _ in by_id]


def rust_table(name, values):
    cells = ["None" if v is None else f"Some({v})" for v in values]
    lines = [f"const {name}: &[Option<u8>] = &["]
    for i in range(0, len(cells), PER_LINE):
        lines.append("    " + ", ".join(cells[i:i + PER_LINE]) + ",")
    lines.append("];")
    return lines


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--old", type=Path, required=True, help="the older version's prepared directory")
    parser.add_argument("--new", type=Path, help="the pinned version's prepared directory (default: .local)")
    parser.add_argument("--out", type=Path)
    args = parser.parse_args()
    old = json.loads((args.old / "datagen/reports/packets.json").read_text())
    old_info = lab.version_info(args.old / "jars/client.jar")
    if args.new:
        new = json.loads((args.new / "datagen/reports/packets.json").read_text())
        info = lab.version_info(args.new / "jars/client.jar")
    else:
        new = json.loads((ROOT / ".local/datagen/out/reports/packets.json").read_text())
        info = lab.version_info()
    old_version, old_protocol = old_info["id"], old_info["protocol_version"]
    module = "v" + old_version.replace(".", "_")
    out = args.out or ROOT / f"crates/horizon-protocol/src/adapter/{module}.rs"
    lines = [
        f"//! Packet ids of protocol {old_protocol} ({old_version}) against the pinned"
        f" {info['protocol_version']} ({info['name']}).",
        "//! Generated by tools/generate_packet_id_adapter.py from both versions' packets reports;",
        "//! do not edit by hand.",
        "use crate::State;",
        "",
        f"pub const PROTOCOL: i32 = {old_protocol};",
        f'pub const NAME: &str = "{old_version}";',
        "",
    ]
    for state in STATES:
        for direction in ["clientbound", "serverbound"]:
            o, n = ids(old, state, direction), ids(new, state, direction)
            # Clientbound: indexed by the old server's id. Serverbound: indexed by Horizon's id.
            values = table(o, n) if direction == "clientbound" else table(n, o)
            assert all(v is None or v < 256 for v in values)
            lines.append("#[rustfmt::skip]")
            lines.extend(rust_table(f"{state.upper()}_{direction.upper()}", values))
    for direction, doc in [
        ("clientbound", f"For each id a {old_version} server sends in `state`, the pinned version's id"
                        " of that packet."),
        ("serverbound", f"For each pinned-version id Horizon sends in `state`, the id a {old_version}"
                        " server knows it by."),
    ]:
        lines.append(f"/// {doc}")
        lines.append(f"pub fn {direction}(state: State) -> &'static [Option<u8>] {{")
        lines.append("    match state {")
        for state in STATES:
            lines.append(f"        State::{state.capitalize()} => {state.upper()}_{direction.upper()},")
        lines.append("    }")
        lines.append("}")
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
